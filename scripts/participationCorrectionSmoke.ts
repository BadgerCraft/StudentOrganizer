import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from 'playwright';
import { installFictionalClassroom } from './helpers/classroomFixture';
const server = await createServer({ server: { host: '127.0.0.1', port: 0, watch: null, hmr: false } });
await server.listen(); const address = server.httpServer!.address(); assert.ok(address && typeof address !== 'string');
const origin = `http://127.0.0.1:${address.port}`;
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || '/usr/bin/chromium' });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors: string[] = [], external: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => route.request().url().startsWith(origin) ? route.continue() : (external.push(route.request().url()), route.abort()));
  await page.goto(origin); await installFictionalClassroom(page); await page.locator('[data-testid^="select-teacher-"]').first().click();
  const card = page.getByTestId('student-seat-card').first(); await card.waitFor();
  assert.equal(await card.getByTestId('open-student-profile-btn').isVisible(), false);
  assert.equal(await card.getByTestId('student-counter-badge').first().isVisible(), false);
  const rows = () => page.evaluate(async () => { const path = '/src/db/database.ts'; return (await import(path)).db.participationEvents.toArray(); });
  const before = await rows();
  await card.getByTestId('student-seat-name').click(); await page.getByTestId('toggle-note-btn').click();
  await page.getByTestId('observation-note-input').fill('Fictional correction acceptance');
  await page.getByTestId('participation-event-btn').filter({ hasNotText: '1–4 Level' }).first().click();
  await page.getByTestId('participation-event-btn').first().waitFor({ state: 'hidden' });
  const afterRecord = await rows(), event = afterRecord.find((row: any) => !before.some((old: any) => old.id === row.id)); assert.ok(event);
  await card.getByTestId('student-seat-name').click();
  const chip = page.locator(`[data-event-id="${event.id}"]`); await chip.waitFor(); await chip.click();
  await chip.waitFor({ state: 'hidden' });
  assert.ok((await rows()).find((row: any) => row.id === event.id).deletedAt);
  await page.getByTestId('toggle-note-btn').click(); await page.getByTestId('observation-note-input').fill('Text editing owns undo');
  await page.keyboard.press('Control+z');
  assert.ok((await rows()).find((row: any) => row.id === event.id).deletedAt, 'typing undo must not restore participation');
  await page.getByTestId('observation-note-input').fill('');
  await card.focus(); await page.keyboard.press('Control+z'); await chip.waitFor();
  const restored = (await rows()).find((row: any) => row.id === event.id);
  assert.equal(restored.deletedAt, null); assert.equal(restored.version, 3); assert.equal(restored.note, event.note);
  assert.equal(restored.batchId, event.batchId); assert.equal((await rows()).length, afterRecord.length);
  const allAfter = await rows(); for (const old of before) assert.deepEqual(allAfter.find((row: any) => row.id === old.id), old);
  await page.getByRole('button', { name: 'Close dock', exact: true }).click();
  await card.getByTestId('student-seat-name').click();
  await page.getByTestId('participation-event-btn').filter({ hasNotText: '1–4 Level' }).first().click();
  await page.getByTestId('participation-event-btn').first().waitFor({ state: 'hidden' });
  const newEvent = (await rows()).find((row: any) => !allAfter.some((old: any) => old.id === row.id)); assert.ok(newEvent);
  await card.focus(); await page.keyboard.press('Control+z');
  await page.waitForFunction(async id => { const path = '/src/db/database.ts'; return !!(await (await import(path)).db.participationEvents.get(id)).deletedAt; }, newEvent.id);
  assert.equal((await rows()).find((row: any) => row.id === event.id).deletedAt, null, 'undo latest record preserves previously restored occurrence');
  await page.getByTestId('classroom-tools-toggle').click(); assert.equal(await card.getByTestId('open-student-profile-btn').isVisible(), true);
  await page.getByTestId('classroom-tools-toggle').click();
  await mkdir('/tmp/student-organizer-ui-evidence', { recursive: true });
  await page.screenshot({ path: '/tmp/student-organizer-ui-evidence/class-participation.png', fullPage: true });
  assert.deepEqual(errors, []); assert.deepEqual(external, []);
  console.log('PASS: production App sparse participation, record-dismiss, today exact-event correction, Ctrl+Z restores same event and undoes a later record, editable undo guard, unchanged history, retained classroom tools.');
} finally { await browser.close(); await server.close(); }
