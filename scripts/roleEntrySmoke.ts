import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { preview } from 'vite';
import { chromium } from 'playwright';
const server = await preview({ preview: { host: '127.0.0.1', port: 4237, strictPort: true } });
let browser;
try {
  browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || '/usr/bin/chromium' });
  const page = await browser.newPage({ viewport: { width: 1280, height: 850 } });
  const errors: string[] = [], external: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => { if (!route.request().url().startsWith('http://127.0.0.1:4237/')) { external.push(route.request().url()); return route.abort(); } return route.continue(); });
  await page.goto('http://127.0.0.1:4237/roles.html');
  await page.getByRole('heading', { name: 'Choose your role' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Student Currently unavailable' }).isDisabled(), true);
  assert.deepEqual(await page.evaluate(async () => (await indexedDB.databases()).map(db => db.name)), []);
  await mkdir('artifacts/roles', { recursive: true });
  await page.screenshot({ path: 'artifacts/roles/chooser-dark.png' });
  await page.keyboard.press('Tab');
  assert.equal(await page.getByRole('button', { name: 'Administrator Open Control Panel' }).evaluate(element => element === document.activeElement), true);
  await page.keyboard.press('Enter');
  await page.getByRole('heading', { name: 'Control Panel', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Import candidate + verify installer' }).isDisabled(), true);
  assert.deepEqual(await page.evaluate(async () => (await indexedDB.databases()).map(db => db.name)), []);
  await page.screenshot({ path: 'artifacts/roles/administrator.png', fullPage: true });
  await page.getByLabel('Verification evidence (no personal or student data)').fill('Fictional unsaved notes');
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('button', { name: 'Choose another role' }).click();
  assert.equal(await page.getByLabel('Verification evidence (no personal or student data)').inputValue(), 'Fictional unsaved notes');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Choose another role' }).click();
  await page.getByRole('heading', { name: 'Choose your role' }).waitFor();
  await page.setViewportSize({ width: 820, height: 850 });
  await page.evaluate(() => { document.documentElement.classList.remove('dark'); document.documentElement.dataset.theme = 'light'; });
  await page.screenshot({ path: 'artifacts/roles/chooser-light-compact.png' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole('button', { name: 'Teacher Open your classroom workspace' }).click();
  await page.getByRole('heading', { name: 'Enter Teacher here', exact: true }).waitFor();
  await page.getByLabel('Teacher name', { exact: true }).fill('Avery Fictional');
  await page.getByRole('button', { name: 'Save and use teacher', exact: true }).click();
  await page.getByTestId('teacher-selector-modal').waitFor({ state: 'hidden' });
  await page.reload();
  await page.getByRole('heading', { name: 'Choose your role' }).waitFor();
  await page.getByRole('button', { name: 'Teacher Open your classroom workspace' }).click();
  assert.match(await page.getByTestId('header-teacher-btn').innerText(), /Avery Fictional/);
  assert.deepEqual(errors, []); assert.deepEqual(external, []);
  console.log('PASS: role entry, disabled student, keyboard navigation, admin isolation, back cancellation, teacher identity/reload, responsive screenshots, no external requests. Native actions require separate checks.');
} finally { await browser?.close(); await new Promise<void>(resolve => server.httpServer!.close(() => resolve())); }
